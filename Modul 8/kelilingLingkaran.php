<?php

// Latihan 5: Menghitung keliling lingkaran dengan jari-jari 15 cm
$r = 15;
$pi = 3.14;

// Menghitung hasil keliling
$keliling = 2 * $pi * $r;

echo "<h2>Hitung Keliling Lingkaran</h2>";
echo "Jari-jari (r) = $r cm <br>";
echo "Nilai Pi = $pi <br>";
echo "Rumus = 2 x Pi x r <br>";
echo "Hasil Keliling = $keliling cm";
?>